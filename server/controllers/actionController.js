const Project = require('../models/Project');
const User = require('../models/User');
const Snag = require('../models/Snag');
const Task = require('../models/Task');
const { isValidObjectId } = require('../middleware/validateRequest');

/**
 * POST /api/actions/execute
 * Executes user-confirmed write actions.
 * Generates fresh database IDs and server-side timestamps.
 */
async function executeAction(req, res, next) {
  try {
    const actionData = req.body.action || req.body;
    const { actionType, projectId, payload } = actionData;

    // 1. Validate & resolve Project (explicit ID if provided, otherwise demo project)
    const { getActiveProject } = require('../services/projectService');
    const project = await getActiveProject(projectId);
    if (!project) {
      return res.status(400).json({
        success: false,
        message: 'Cannot execute action without an active project.',
      });
    }

    // 2. Handle CREATE_SNAG
    if (actionType === 'CREATE_SNAG') {
      const { title, location, priority = 'Medium', assigneeId, description } = payload || {};

      if (!isValidObjectId(assigneeId)) {
        return res.status(400).json({
          success: false,
          message: 'Invalid assigneeId format in action payload.',
        });
      }

      const assignee = await User.findById(assigneeId);
      if (!assignee) {
        return res.status(404).json({
          success: false,
          message: `Assigned user/contractor with ID "${assigneeId}" not found.`,
        });
      }

      const allowedPriorities = ['Low', 'Medium', 'High', 'Critical'];
      const validPriority = allowedPriorities.includes(priority) ? priority : 'Medium';

      const reporterId = req.user ? req.user._id : (payload?.reporterId || null);
      const reporterName = req.user ? req.user.name : (payload?.reporterName || '');

      // Construct server-authoritative document (IDs and timestamps generated by MongoDB)
      const newSnag = await Snag.create({
        projectId: project._id,
        title: title ? title.trim() : 'Problem item',
        location: location ? location.trim() : 'Site / General',
        priority: validPriority,
        assigneeId: assignee._id,
        reporterId,
        reporterName,
        description: (description || '').trim(),
        status: 'Open',
      });

      const populatedSnag = await Snag.findById(newSnag._id)
        .populate('assigneeId', 'name role')
        .populate('reporterId', 'name role email')
        .lean();

      const spokenResponse = `Done. Recorded problem "${newSnag.title}" for ${newSnag.location}, assigned to ${assignee.name}.`;

      return res.status(201).json({
        success: true,
        actionType,
        data: populatedSnag,
        record: populatedSnag,
        spokenResponse,
      });
    }

    // 3. Handle CREATE_TASK
    if (actionType === 'CREATE_TASK') {
      const { title, dueDate, assigneeId, description } = payload || {};

      const { createTaskRecord } = require('../services/taskService');
      const { task, assignee } = await createTaskRecord({
        projectId: project._id,
        title,
        dueDate,
        assigneeId,
        description,
        status: 'Pending',
      });

      const dateStr = task.dueDate ? ` for ${new Date(task.dueDate).toLocaleDateString()}` : '';
      const spokenResponse = `Command processed successfully. Scheduled task "${task.title}"${dateStr}, assigned to ${assignee.name}.`;

      return res.status(201).json({
        success: true,
        message: 'Command processed successfully.',
        actionType,
        data: task,
        record: task,
        spokenResponse,
      });
    }

    return res.status(400).json({
      success: false,
      message: `Unsupported action type "${actionType}".`,
    });
  } catch (err) {
    next(err);
  }
}

module.exports = {
  executeAction,
};
